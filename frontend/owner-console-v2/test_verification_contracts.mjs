import assert from 'node:assert/strict';
import { exactDisplay, sameIdentities, authorityEvidence } from './verification_contracts.mjs';
assert.equal(exactDisplay('13 / 30', '3 / 3'), false);
assert.equal(exactDisplay('154', '54'), false);
assert.equal(exactDisplay('-2.35 USDT', '+2.35 USDT'), false);
assert.equal(exactDisplay(' 1,234.50 USDT ', '1234.50 USDT'), true);
assert.equal(sameIdentities(['a','b'], ['a']), false);
assert.equal(sameIdentities(['a','a'], ['a']), false);
assert.equal(sameIdentities(['b','a'], ['a','b']), true);
const orb = (a) => ({runtime:{current_authority:a ? {authority:a}:null}});
const a = {selection_authority_id:'a',authority_outcome:'ACTIVE_NEW',effective_from_ms:100,expires_at_ms:200};
assert.equal(authorityEvidence('orb',orb(null),150).state,'missing');
assert.equal(authorityEvidence('orb',orb(a),99).state,'pending');
assert.equal(authorityEvidence('orb',orb(a),100).state,'active');
assert.equal(authorityEvidence('orb',orb(a),200).state,'expired');
assert.equal(authorityEvidence('orb',orb({...a,expires_at_ms:null}),150).complete,false);
const g = {runtime:{current_authority_id:'g',current_authority_outcome:'ACTIVE_NEW',membership_valid_until_ms:200,first_blocker:null}};
assert.equal(authorityEvidence('generic',g,200).state,'expired');
assert.equal(authorityEvidence('generic',g,150).state,'active');
assert.equal(authorityEvidence('generic',{runtime:{installed:true}},150).state,'missing');
console.log('16 verification contract assertions passed');
